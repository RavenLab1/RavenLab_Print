let language = localStorage.getItem("ravenlab_print_lang") || "ar";
let currentProduct = "business";
let selected = {size:"",material:"",finish:"",quantity:100,orderType:"ready"};
let cart = JSON.parse(localStorage.getItem("ravenlab_print_cart") || "[]");

const $ = id => document.getElementById(id);

function formatIQD(value){
  return `${Math.round(Number(value)||0).toLocaleString("en-US")} د.ع`;
}

function setLanguage(lang){
  language = i18n[lang] ? lang : "ar";
  localStorage.setItem("ravenlab_print_lang", language);
  document.documentElement.lang = language;
  document.documentElement.dir = language === "en" ? "ltr" : "rtl";
  document.body.classList.toggle("ltr", language === "en");
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.dataset.i18n;
    if(i18n[language][key] !== undefined){
      if(key === "hero_title") el.innerHTML = i18n[language][key];
      else el.textContent = i18n[language][key];
    }
  });
  document.querySelectorAll(".lang-btn").forEach(btn=>btn.classList.toggle("active",btn.dataset.lang===language));
  renderModal();
  renderCart();
}

function label(key){ return i18n[language][key] || key; }

function openProduct(key){
  currentProduct = key;
  const p = productData[key];
  selected = {
    size:p.sizes[0],
    material:p.materials[0],
    finish:p.finishes[0],
    quantity:100,
    orderType:"ready"
  };
  renderModal();
  $("modalBackdrop").classList.add("open");
  $("productModal").classList.add("open");
  $("productModal").setAttribute("aria-hidden","false");
  document.body.style.overflow = "hidden";
}
function closeProduct(){
  $("modalBackdrop").classList.remove("open");
  $("productModal").classList.remove("open");
  $("productModal").setAttribute("aria-hidden","true");
  document.body.style.overflow = "";
}

function makeOptions(host, values, selectedValue, type){
  host.innerHTML = values.map(v=>`<button class="option ${v===selectedValue?"active":""}" type="button" data-choice="${type}" data-value="${v}">${v}</button>`).join("");
}

function nearestPackagePrice(qty){
  const p = productData[currentProduct];
  const tiers = Object.keys(p.basePrices).map(Number).sort((a,b)=>a-b);
  if(p.basePrices[qty]) return p.basePrices[qty];
  let lower = tiers.filter(t=>t<=qty).pop() || tiers[0];
  let unit = p.basePrices[lower] / lower;
  // Custom quantities get a small scale discount after each tier.
  if(qty>lower) unit *= 0.97;
  return Math.max(0,Math.round(unit*qty/500)*500);
}
function currentPrice(){
  let price = nearestPackagePrice(Number(selected.quantity)||1);
  if(selected.orderType==="custom" && productData[currentProduct].sticker) price += 5000;
  if(selected.material.includes("Premium")) price += 3000;
  if(selected.material.includes("Glossy")) price += 2000;
  return price;
}

function renderModal(){
  const p = productData[currentProduct];
  if(!p) return;
  $("modalImage").src = p.image;
  $("modalThumb").src = p.image;
  $("modalImage").alt = label(p.nameKey);
  $("modalTitle").textContent = label(p.nameKey);
  $("modalDescription").textContent = label(p.descKey);
  $("modalBreadcrumb").textContent = `RavenLab / Print / ${label(p.nameKey)}`;
  $("orderTypeGroup").style.display = p.sticker ? "" : "none";

  makeOptions($("sizeOptions"),p.sizes,selected.size,"size");
  makeOptions($("materialOptions"),p.materials,selected.material,"material");
  makeOptions($("finishOptions"),p.finishes,selected.finish,"finish");

  $("quantityOptions").innerHTML = [50,100,200,500,1000].map(q=>`
    <button class="quantity-option ${Number(selected.quantity)===q?"active":""}" type="button" data-qty="${q}">
      <b>${q}</b><small>${formatIQD(p.basePrices[q])}</small>
    </button>`).join("");

  document.querySelectorAll("[data-order-type]").forEach(btn=>btn.classList.toggle("active",btn.dataset.orderType===selected.orderType));
  $("modalPrice").textContent = formatIQD(currentPrice());
}
function chooseOption(type,value){
  selected[type]=value;
  renderModal();
}
function chooseQuantity(qty){
  selected.quantity = Number(qty);
  $("customQuantity").value="";
  renderModal();
}

function addCurrentToCart(){
  const p=productData[currentProduct];
  cart.push({
    id:crypto.randomUUID ? crypto.randomUUID() : `${Date.now()}-${Math.random()}`,
    product:currentProduct,
    name:label(p.nameKey),
    size:selected.size,
    material:selected.material,
    finish:selected.finish,
    quantity:Number(selected.quantity),
    orderType:selected.orderType,
    price:currentPrice()
  });
  saveCart();
  closeProduct();
  openCart();
}
function saveCart(){
  localStorage.setItem("ravenlab_print_cart",JSON.stringify(cart));
  $("cartCount").textContent=cart.length;
  renderCart();
}
function renderCart(){
  $("cartCount").textContent=cart.length;
  $("cartEmpty").style.display=cart.length ? "none" : "block";
  $("cartItems").innerHTML = cart.map(item=>`
    <div class="cart-item">
      <div class="cart-item-top">
        <div>
          <h4>${label(productData[item.product].nameKey)}</h4>
          <p>${item.quantity} × ${item.size} · ${item.material} · ${item.finish}</p>
          ${productData[item.product].sticker?`<p>${item.orderType==="custom"?label("custom_design"):label("ready_designs")}</p>`:""}
        </div>
        <button class="remove-item" data-remove="${item.id}" type="button">×</button>
      </div>
      <p><b>${formatIQD(item.price)}</b></p>
    </div>`).join("");
  const total=cart.reduce((s,i)=>s+Number(i.price||0),0);
  $("cartTotal").textContent=formatIQD(total);
}
function openCart(){
  $("drawerBackdrop").classList.add("open");
  $("cartDrawer").classList.add("open");
  $("cartDrawer").setAttribute("aria-hidden","false");
}
function closeCart(){
  $("drawerBackdrop").classList.remove("open");
  $("cartDrawer").classList.remove("open");
  $("cartDrawer").setAttribute("aria-hidden","true");
}
function removeCartItem(id){
  cart=cart.filter(i=>i.id!==id);
  saveCart();
}

function productMessage(item){
  const p=productData[item.product];
  const orderType=p.sticker ? (item.orderType==="custom"?label("custom_design"):label("ready_designs")) : "-";
  return [
    `${label(p.nameKey)}`,
    `${label("quantity_label")}: ${item.quantity}`,
    `${label("size_label")}: ${item.size}`,
    `${label("material_label")}: ${item.material}`,
    `${label("finish_label")}: ${item.finish}`,
    p.sticker?`${label("type_label")}: ${orderType}`:"",
    `${label("estimated_total")}: ${formatIQD(item.price)}`
  ].filter(Boolean).join("\n");
}
function openWhatsApp(text){
  window.open(`https://wa.me/${WHATSAPP}?text=${encodeURIComponent(text)}`,"_blank","noopener");
}
function sendCurrentWhatsApp(){
  const p=productData[currentProduct];
  const item={
    product:currentProduct,
    quantity:selected.quantity,size:selected.size,material:selected.material,finish:selected.finish,
    orderType:selected.orderType,price:currentPrice()
  };
  const intro = language==="en" ? "Hello RavenLab, I would like to order:" : language==="ku" ? "سڵاو RavenLab، دەمەوێت ئەم داواکارییە بکەم:" : "مرحباً RavenLab، أريد طلب:";
  openWhatsApp(`${intro}\n\n${productMessage(item)}\n\n${label("price_note")}`);
}
function sendCart(){
  if(!cart.length) return;
  const intro = language==="en" ? "Hello RavenLab, I would like to order:" : language==="ku" ? "سڵاو RavenLab، دەمەوێت ئەم داواکارییە بکەم:" : "مرحباً RavenLab، أريد تثبيت هذا الطلب:";
  const body=cart.map((item,i)=>`${i+1}) ${productMessage(item)}`).join("\n\n");
  const total=cart.reduce((s,i)=>s+Number(i.price||0),0);
  openWhatsApp(`${intro}\n\n${body}\n\n${label("cart_total")}: ${formatIQD(total)}\n${label("price_note")}`);
}

